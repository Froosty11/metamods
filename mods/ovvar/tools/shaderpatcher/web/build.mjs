// Writes dist/resources.generated.ts: the five GLSL files as strings, and the stamp.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadResources } from './resources.mjs';

const res = loadResources();
const out = fileURLToPath(new URL('./dist/', import.meta.url));
mkdirSync(out, { recursive: true });
const body = `// Generated by build.mjs from the GLSL sources; do not edit.
import type { Resources } from '../patcher.ts';

export const STAMP = ${JSON.stringify(res.stamp)};

export const resources: Resources = {
	ovvar: ${JSON.stringify(res.ovvar)},
	riftCommon: ${JSON.stringify(res.riftCommon)},
	voidRift: ${JSON.stringify(res.voidRift)},
	netherRift: ${JSON.stringify(res.netherRift)},
	textColors: ${JSON.stringify(res.textColors)},
	stamp: STAMP,
};
`;
writeFileSync(out + 'resources.generated.ts', body);
console.log('wrote dist/resources.generated.ts, stamp ' + res.stamp);
